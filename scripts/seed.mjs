// -------------------------------------------------------------
// 2. Seeding Execution Logic
// -------------------------------------------------------------
async function main() {
  console.log('🌱 Starting Emdad Dental Database Seeding...');

  // A. Admin User
  const adminEmail = 'admin@emdad-dental.com';
  const rawPassword = 'admin123';
  const passwordHash = await bcrypt.hash(rawPassword, 10);

  const admin = await prisma.adminUser.upsert({
    where: { email: adminEmail },
    update: {
      name: 'مدير إمداد السريري',
      passwordHash,
      role: 'ADMIN',
    },
    create: {
      email: adminEmail,
      name: 'مدير إمداد السريري',
      passwordHash,
      role: 'ADMIN',
    },
  });
  console.log(`✅ Admin user ready: ${admin.email}`);

  // B. Store Settings
  const settings = await prisma.storeSettings.upsert({
    where: { id: STORE_SETTINGS_DATA.id },
    update: STORE_SETTINGS_DATA,
    create: STORE_SETTINGS_DATA,
  });
  console.log(`✅ Store settings seeded: ${settings.storeName}`);

  // C. Categories
  for (const cat of CATEGORIES_DATA) {
    await prisma.category.upsert({
      where: { slug: cat.slug },
      update: cat,
      create: cat,
    });
  }
  console.log(`✅ Seeded ${CATEGORIES_DATA.length} clinical categories`);

  // D. Products
  for (const prod of PRODUCTS_DATA) {
    await prisma.product.upsert({
      where: { sku: prod.sku },
      update: prod,
      create: prod,
    });
  }
  console.log(`✅ Seeded ${PRODUCTS_DATA.length} dental products with SYP prices`);

  // E. Banners
  for (const banner of BANNERS_DATA) {
    await prisma.banner.upsert({
      where: { id: banner.id },
      update: banner,
      create: banner,
    });
  }
  console.log(`✅ Seeded ${BANNERS_DATA.length} promotional banners`);

  console.log('🎉 Database seeding completed successfully!');
}

main()
  .catch((e) => {
    console.error('❌ Seeding failed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
