// Helper query functions
export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function getProductBySku(sku: string): Product | undefined {
  return PRODUCTS.find((p) => p.sku === sku);
}

export function getProductsByCategory(categoryId: string): Product[] {
  if (categoryId === 'all') return PRODUCTS;
  return PRODUCTS.filter((p) => p.categoryId === categoryId);
}

export function getFeaturedProducts(): Product[] {
  return PRODUCTS.filter((p) => p.featured);
}

export function searchProducts(query: string, categoryId?: string): Product[] {
  const normalized = query.trim().toLowerCase();
  let list = PRODUCTS;

  if (categoryId && categoryId !== 'all') {
    list = list.filter((p) => p.categoryId === categoryId);
  }

  if (!normalized) return list;

  return list.filter((p) => {
    return (
      p.name.toLowerCase().includes(normalized) ||
      (p.nameEn && p.nameEn.toLowerCase().includes(normalized)) ||
      p.description.toLowerCase().includes(normalized) ||
      (p.technicalSpecs && p.technicalSpecs.some((s) => s.toLowerCase().includes(normalized)))
    );
  });
}

export function formatPriceSYP(amount: number): string {
  return new Intl.NumberFormat('ar-SY').format(amount);
}
